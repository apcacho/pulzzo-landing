// Keep CSS authoring in assets/css. Commit the generated adapter for static hosting.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {transform} from 'esbuild';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const sources=['assets/css/crm-demo.css','assets/css/crm-demo-embed.css'];
const parts=[];
for (const name of sources) {
  const css=fs.readFileSync(path.join(root,name),'utf8');
  // Relative assets would resolve against the document instead of the CSS file.
  // Refuse them until the build supports URL rebasing; current assets are data URLs.
  if (/@import\b/i.test(css)) throw new Error(`${name}: external imports are not allowed in the synchronous CRM styles`);
  for (const match of css.matchAll(/url\(\s*(['"]?)(.*?)\1\s*\)/gi)) {
    if (!/^(?:data:|#)/i.test(match[2])) throw new Error(`${name}: external CSS URL requires an explicit bundling strategy`);
  }
  const checked=await transform(css,{loader:'css',logLevel:'silent'});
  if (checked.warnings.length) throw new Error(`${name}: ${JSON.stringify(checked.warnings)}`);
  parts.push(css);
}
const template=fs.readFileSync(path.join(root,'scripts/crm-demo-embed.source.js'),'utf8');
const marker=JSON.stringify('__PULZZO_CRM_CSS__');
if (template.split(marker).length!==2) throw new Error('Expected exactly one CRM stylesheet build marker');
const output='/* GENERATED by scripts/build-crm-embed.mjs. Sources, in cascade order: '+sources.map(s=>"'"+s+"'").join(', ')+'. */\n'+template.replace(marker,()=>JSON.stringify(parts.join('\n')));
const target=path.join(root,'assets/js/crm-demo-embed.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target,'utf8')!==output) throw new Error('Stale CRM embedding bundle. Run npm run build:crm and commit the generated asset.');
  console.log('PASS: CRM embedding bundle matches its adapter and canonical CSS sources.');
} else {
  fs.writeFileSync(target,output);
  console.log(`Built CRM embedding with synchronous scoped CSS (${Buffer.byteLength(output)} bytes).`);
}
