export function isPublicPath(relative){
 if(typeof relative!=='string'||relative.includes('\\')||relative.split('/').some(part=>!part||part.startsWith('.')))return false;
 return PUBLIC_PAGES.has(relative)||PUBLIC_ASSETS.has(relative);
}

export async function collectPublicAssets(root,{allowMissing=[]}={}){
 const result=[];
 async function add(relative){
  const absolute=path.join(root,...relative.split('/'));
  const stat=await fs.lstat(absolute);
  if(stat.isSymbolicLink()||!stat.isFile())throw Error(`Public assets must be regular files: ${relative}`);
  if(!isPublicPath(relative))throw Error(`Unapproved public file: ${relative}`);
  result.push(relative);
 }
 for(const name of await fs.readdir(root))if(name.endsWith('.html'))await add(name);
 // Missing app pages are a broken build rather than a silently incomplete site.
 for(const name of PUBLIC_PAGES)if(!result.includes(name))throw Error(`Missing public page: ${name}`);
 async function walk(relative){
  const stat=await fs.lstat(path.join(root,...relative.split('/')));
  if(stat.isSymbolicLink()||!stat.isDirectory())throw Error(`Public assets must use real directories: ${relative}`);
  for(const name of await fs.readdir(path.join(root,...relative.split('/')))){
   const child=relative+'/'+name,entry=await fs.lstat(path.join(root,...child.split('/')));
   if(entry.isDirectory()){
    if(!/^assets\/(?:js|css|favicon|images|social|pdfjs(?:\/(?:cmaps|standard_fonts|wasm))?)$/.test(child))throw Error(`Unapproved public directory: ${child}`);
    await walk(child);
   }else await add(child);
  }
 }
 await walk('assets');
 for(const name of PUBLIC_ASSETS)if(!result.includes(name)&&!allowMissing.includes(name))throw Error(`Missing public asset: ${name}`);
 return result.sort();
}
