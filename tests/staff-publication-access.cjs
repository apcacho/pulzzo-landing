'use strict';
const assert=require('node:assert/strict');
const Staff=require('../assets/js/staff-access.js');
const Publication=require('../assets/js/doctor-publication.js');
const values=new Map(),storage={getItem:k=>values.get(k)??null,setItem:(k,v)=>values.set(k,String(v)),removeItem:k=>values.delete(k)};
const staff=Staff.createStore({storage});
const admin=staff.loginDemo('admin@pulzzo.mx','pulzzo-demo');
staff.updateUser(admin,'kam_ana',{roles:['kam','leader','operations']});
const mixed=staff.loginDemo('ana.kam@pulzzo.mx','pulzzo-demo');
const providers={own:{id:'own',doctorAccountId:'holder_own',contactId:'contact_own',assignedKam:'kam_ana',eligible:true},other:{id:'other',doctorAccountId:'holder_other',contactId:'contact_other',assignedKam:'kam_luis',eligible:true}};
const fields={displayName:'Doctora demo',specialty:'Dermatología',city:'CDMX',state:'CDMX',clinicName:'Clínica demo',bio:'Atención demo.',phone:'5512345678',whatsapp:'5512345678',website:'',services:['Consulta'],links:{},photo:null};
const make=(session,actor)=>Publication.createStore({storage,staffAccess:staff,staffSession:session,actor:actor||staff.getActor(session),resolveProvider:id=>providers[id]});
const owner=make(mixed);
owner.saveDraft('own',fields,0);
assert.equal(owner.snapshot().profiles.own.versions[0].createdBy,'kam_ana');
assert.equal(owner.snapshot().profiles.own.versions[0].createdRole,'leader');
assert.throws(()=>owner.saveDraft('other',fields,1),e=>e.code==='forbidden');
assert.throws(()=>make(mixed,{id:'admin_demo',role:'admin'}).snapshot(),e=>e.code==='forbidden');
assert.throws(()=>owner.review('own',owner.snapshot().profiles.own.currentVersionId,'approve','',1),e=>e.code==='reviewer_required');
staff.updateUser(admin,'kam_ana',{active:false});
assert.throws(()=>owner.snapshot(),e=>e.code==='forbidden');
assert.throws(()=>owner.saveDraft('own',fields,1),e=>e.code==='forbidden');
const provider=staff.loginDemo('medicos@pulzzo.mx','pulzzo-demo');
const reviewer=make(provider,{id:provider.id,role:'admin'});
reviewer.saveDraft('other',fields,1);
assert.equal(reviewer.snapshot().profiles.other.versions[0].createdBy,'provider_demo');
staff.loginDemo('lectura@pulzzo.mx','pulzzo-demo');
assert.throws(()=>reviewer.snapshot(),e=>e.code==='forbidden');
const freshProvider=staff.loginDemo('medicos@pulzzo.mx','pulzzo-demo');
const currentReviewer=make(freshProvider,{id:freshProvider.id,role:'admin'});
assert.equal(currentReviewer.snapshot().profiles.other.versions.length,1);
const role=staff.listRoles(admin).find(r=>r.id==='provider');
staff.updateRole(admin,'provider',{grants:{...role.grants,providerActions:'none'}});
assert.throws(()=>currentReviewer.saveDraft('other',fields,2),e=>e.code==='forbidden');
console.log('PASS: publication staff identity, mixed-role own edits, impersonation, revocation and configured permission removal');
